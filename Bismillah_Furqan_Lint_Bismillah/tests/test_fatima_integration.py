# Checker: sidecar diagnostics
# ---------------------------------------------------------------------------

class TestChecker:
    """check_fatima_integrity produces the right diagnostics."""

    def test_no_sidecar_returns_no_diags(self, tmp_path):
        # A file with no sidecar — check should be silent (no seal to verify).
        mod = tmp_path / "clean.py"
        mod.write_text("x = 1\n", encoding="utf-8")
        diags = check_fatima_integrity(mod)
        # No sidecar → either empty (nothing to check) or a single
        # "no attestation" diagnostic — both are acceptable.
        assert isinstance(diags, list)

    def test_valid_sidecar_returns_no_diags(self, tmp_path):
        mod = tmp_path / "sealed.py"
        mod.write_text("y = 2\n", encoding="utf-8")
        seal_and_write(mod)
        diags = check_fatima_integrity(mod)
        assert diags == []

    def test_tampered_file_returns_diags(self, tmp_path):
        mod = tmp_path / "tamper.py"
        mod.write_text("z = 3\n", encoding="utf-8")
        seal_and_write(mod)
        mod.write_text("z = 999\n", encoding="utf-8")  # tamper
        diags = check_fatima_integrity(mod)
        assert len(diags) >= 1
        assert any("seal" in d.diagnosis.lower() or "integrity" in d.diagnosis.lower()
                    or "mismatch" in d.diagnosis.lower()
                    for d in diags)


class TestSealDirectory:
    """seal_directory must create sidecars for every .py file."""

    def test_seals_all_py_files(self, tmp_path):
        (tmp_path / "a.py").write_text("a = 1\n", encoding="utf-8")
        (tmp_path / "b.py").write_text("b = 2\n", encoding="utf-8")
        (tmp_path / "sub").mkdir()
        (tmp_path / "sub" / "c.py").write_text("c = 3\n", encoding="utf-8")
        seal_directory(tmp_path)
        for name in ["a.py", "b.py"]:
            sidecar = tmp_path / (name + FATIMA_SIDECAR_SUFFIX)
            assert sidecar.exists(), f"Missing sidecar for {name}"
        assert (tmp_path / "sub" / ("c.py" + FATIMA_SIDECAR_SUFFIX)).exists()


