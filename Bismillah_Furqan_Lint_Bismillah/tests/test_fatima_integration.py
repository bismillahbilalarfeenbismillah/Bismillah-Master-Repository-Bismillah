# FatimaAttestation round-trip
# ---------------------------------------------------------------------------

class TestFatimaAttestation:
    """FatimaAttestation serialisation must round-trip cleanly."""

    def test_to_dict_from_dict_roundtrip(self):
        att = FatimaAttestation(
            module_path="test.py",
            master_seal="a" * 64,
            heaven_seals=["b" * 64] * 11,
            encoder_version="1.0.0",
            architecture="154-layer-dual-constant",
        )
        d = att.to_dict()
        att2 = FatimaAttestation.from_dict(d)
        assert att2.module_path == att.module_path
        assert att2.master_seal == att.master_seal
        assert att2.encoder_version == att.encoder_version

    def test_to_json_is_valid(self):
        att = FatimaAttestation(
            module_path="test.py",
            master_seal="a" * 64,
            heaven_seals=["c" * 64] * 11,
            encoder_version="1.0.0",
            architecture="154-layer-dual-constant",
        )
        j = att.to_json()
        parsed = json.loads(j)
        assert parsed["module_path"] == "test.py"


