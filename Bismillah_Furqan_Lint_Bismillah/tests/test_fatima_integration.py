# Seal computation
# ---------------------------------------------------------------------------

class TestComputeSeal:
    """compute_seal must be deterministic and return hex SHA-256."""

    def test_deterministic(self):
        content = b"Bismillah ir-Rahman ir-Rahim"
        s1 = compute_seal(content)
        s2 = compute_seal(content)
        assert s1 == s2

    def test_hex_length(self):
        seal = compute_seal(b"test content")
        # SHA-256 hex is 64 characters
        assert len(seal) == 64
        assert all(c in "0123456789abcdef" for c in seal)

    def test_different_content_different_seal(self):
        s1 = compute_seal(b"content A")
        s2 = compute_seal(b"content B")
        assert s1 != s2


