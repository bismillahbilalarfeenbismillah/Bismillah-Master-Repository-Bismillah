class TestModuleSealVerify:
    """seal_module and verify_module must agree on unchanged files."""

    def test_seal_and_verify_pass(self, tmp_path):
        mod = tmp_path / "example.py"
        mod.write_text("# Bismillah\nprint('hello')\n", encoding="utf-8")
        att = seal_module(mod)
        assert att.master_seal
        ok, findings = verify_module(mod, att)
        assert ok is True
        assert findings == []

    def test_verify_fails_on_tampered_content(self, tmp_path):
        mod = tmp_path / "example.py"
        mod.write_text("# original\n", encoding="utf-8")
        att = seal_module(mod)
        mod.write_text("# tampered\n", encoding="utf-8")
        ok, findings = verify_module(mod, att)
        assert ok is False
        assert len(findings) > 0


