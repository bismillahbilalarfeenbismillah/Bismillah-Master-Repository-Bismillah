# CLI dispatchers (unit-level — no subprocess)
# ---------------------------------------------------------------------------

class TestCLI:
    """Smoke-test the CLI dispatch functions."""

    def test_cmd_seal_on_single_file(self, tmp_path):
        from furqan_lint.fatima.cli import cmd_seal

        mod = tmp_path / "target.py"
        mod.write_text("val = 42\n", encoding="utf-8")
        rc = cmd_seal([str(mod)])
        assert rc == 0
        assert (tmp_path / ("target.py" + FATIMA_SIDECAR_SUFFIX)).exists()

    def test_cmd_seal_on_directory(self, tmp_path):
        from furqan_lint.fatima.cli import cmd_seal

        (tmp_path / "one.py").write_text("one = 1\n", encoding="utf-8")
        rc = cmd_seal([str(tmp_path)])
        assert rc == 0

    def test_cmd_unseal_removes_sidecars(self, tmp_path):
        from furqan_lint.fatima.cli import cmd_seal, cmd_unseal

        mod = tmp_path / "rm_me.py"
        mod.write_text("rm = True\n", encoding="utf-8")
        cmd_seal([str(mod)])
        sidecar = tmp_path / ("rm_me.py" + FATIMA_SIDECAR_SUFFIX)
        assert sidecar.exists()
        rc = cmd_unseal([str(mod)])
        assert rc == 0
        assert not sidecar.exists()


