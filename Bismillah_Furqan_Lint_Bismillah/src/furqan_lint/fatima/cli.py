"""CLI dispatch for FATIMA subcommands.

Subcommands:
  furqan-lint seal <path>        -- Seal module(s) with FATIMA attestation
  furqan-lint seal <directory>   -- Seal all .py files recursively
  furqan-lint unseal <path>      -- Remove FATIMA sidecar(s)

The --fatima flag on ``furqan-lint check`` is handled in the main
CLI module (cli.py) and delegates to checker.check_fatima_integrity.
"""

from __future__ import annotations

import sys
from pathlib import Path

from furqan_lint.fatima.checker import (
    FATIMA_SIDECAR_SUFFIX,
    seal_and_write,
    seal_directory,
)
from furqan_lint.fatima.encoder import BISMILLAH


def cmd_seal(args: list[str]) -> int:
    """Handle ``furqan-lint seal <path>``."""
    if not args:
        print("furqan-lint seal: requires a path argument", file=sys.stderr)
        return 2

    target = Path(args[0])
    if not target.exists():
        print(f"Not found: {target}", file=sys.stderr)
        return 1

    print(f"  {BISMILLAH}")
    print()

    if target.is_file():
        att = seal_and_write(target)
        print(f"  Sealed: {att.module_path}")
        print(f"    Master seal: {att.master_seal[:32]}...")
        print(f"    Architecture: {att.architecture}")
        print(f"    Heavens: {len(att.heaven_seals)}")
        print(f"    Sidecar: {target.name}{FATIMA_SIDECAR_SUFFIX}")
        return 0

    # Directory seal
    attestations = seal_directory(target)
    if not attestations:
        print(f"  No Python files found in {target}", file=sys.stderr)
        return 1

    print(f"  Sealed {len(attestations)} modules in {target}")
    for att in attestations:
        print(f"    {att.module_path}: {att.master_seal[:16]}...")
    print()
    print("  Architecture: 154-layer dual-constant (11 heavens x 14 layers)")
    print("  Co-firing disclosed: True")
    return 0


def cmd_unseal(args: list[str]) -> int:
    """Handle ``furqan-lint unseal <path>``."""
    if not args:
        print(
            "furqan-lint unseal: requires a path argument",
            file=sys.stderr,
        )
        return 2

    target = Path(args[0])
    if not target.exists():
        print(f"Not found: {target}", file=sys.stderr)
        return 1

    removed = 0
    if target.is_file():
        sidecar = target.with_suffix(target.suffix + FATIMA_SIDECAR_SUFFIX)
        if sidecar.exists():
            sidecar.unlink()
            print(f"  Removed: {sidecar}")
            removed = 1
        else:
            print(f"  No FATIMA sidecar found for {target}")
    else:
        for sidecar in sorted(target.rglob(f"*{FATIMA_SIDECAR_SUFFIX}")):
            sidecar.unlink()
            print(f"  Removed: {sidecar}")
            removed += 1

    if removed:
        print(f"  Removed {removed} FATIMA sidecar(s)")
    else:
        print("  No FATIMA sidecars found")
    return 0


