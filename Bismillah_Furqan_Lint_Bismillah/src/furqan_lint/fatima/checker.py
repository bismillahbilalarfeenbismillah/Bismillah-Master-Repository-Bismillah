"""FATIMA integrity checker for the furqan-lint pipeline.

This checker runs alongside D24, D11, return_none_mismatch, and
zero_return_path in the runner pipeline. It verifies that source
modules have not been modified since their last FATIMA seal.

Integration model (v0.13.0 — dual-sidecar):

  1. **FATIMA sidecar** (``.fatima.json``): produced by
     ``furqan-lint seal <path>``. Carries master seal + 11-heaven
     seal map from the 154-layer encoder.
  2. **Bismillah witness** (``.witness.bismillah``): produced by
     the Bismillah Divine Protection Encoder. Carries the
     NFC-normalized SHA-256 seal with Bismillah bookends.

  On ``furqan-lint check --fatima <path>``, this checker:
    a. Verifies FATIMA sidecars (master + heaven seals)
    b. Verifies Bismillah witness sidecars (seal hash)
    c. Analyzes import bond integrity (dependency chains)
    d. Produces a hadith-science grade (muhkam through mawdu)

The checker produces Marad-compatible diagnostics so they render
uniformly with the existing furqan-lint output format.

v0.13.0: FATIMA + Bismillah encoder enmeshment. Dual-sidecar
support, bond graph analysis, hadith-science grading.
"""

from __future__ import annotations

import hashlib
import hmac as hmac_mod
import json
import os
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from furqan_lint.fatima.encoder import (
    BISMILLAH,
    FatimaAttestation,
    seal_module,
    verify_module,
)


FATIMA_SIDECAR_SUFFIX = ".fatima.json"
WITNESS_SIDECAR_SUFFIX = ".witness.bismillah"

# Hadith-science grade thresholds (mirror the FATIMA bridge)
GRADE_THRESHOLDS = {
    "muhkam":      0.95,
    "mutashabih":  0.80,
    "hasan":       0.60,
    "da'if":       0.40,
    "mawdu":       0.00,
}


def _grade_score(score: float) -> str:
    """Map a [0.0, 1.0] score to a hadith-science grade."""
    for grade, threshold in GRADE_THRESHOLDS.items():
        if score >= threshold:
            return grade
    return "mawdu"


@dataclass
class FatimaDiagnostic:
    """Diagnostic from the FATIMA integrity checker.

    Modeled on furqan.errors.marad.Marad but independent of
    the furqan package so FATIMA checking can run without the
    furqan dependency (the seal/verify path is self-contained).

    v0.13.0: Extended with grade/score fields for hadith-science
    grading and seal_expected/seal_actual for witness verification.
    """

    primitive: str
    diagnosis: str
    location: str
    minimal_fix: str
    regression_check: str
    grade: Optional[str] = None
    score: Optional[float] = None
    seal_expected: Optional[str] = None
    seal_actual: Optional[str] = None


# ---------------------------------------------------------------------------
# Bismillah witness seal computation (standalone — no encoder import)
# ---------------------------------------------------------------------------


def _compute_bismillah_seal(content_bytes: bytes) -> str:
    """Compute a Bismillah-anchored NFC-normalized SHA-256 seal.

    Mirrors ``compute_seal()`` from the Bismillah encoder but is
    self-contained so furqan-lint doesn't require the encoder as a
    runtime dependency for witness verification.
    """
    if isinstance(content_bytes, str):
        content_bytes = content_bytes.encode("utf-8")
    try:
        text = content_bytes.decode("utf-8")
        normalized = unicodedata.normalize("NFC", text).encode("utf-8")
    except (UnicodeDecodeError, ValueError):
        normalized = content_bytes

    h = hashlib.sha256()
    h.update(BISMILLAH.encode("utf-8"))
    h.update(normalized)
    h.update(BISMILLAH.encode("utf-8"))
    return h.hexdigest()


def _extract_witness_seal(witness_path: str) -> Optional[str]:
    """Extract the muhkam_seal from a .witness.bismillah sidecar.

    Reads the JSON sidecar and returns the seal value, checking
    multiple key variants for version compatibility.
    """
    try:
        with open(witness_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        for key in ("muhkam_seal", "seal", "computation"):
            if key in data:
                val = data[key]
                if isinstance(val, str) and len(val) == 64:
                    return val
                if isinstance(val, dict):
                    for subkey in ("muhkam_seal", "seal", "master_witness"):
                        if subkey in val and isinstance(val[subkey], str):
                            return val[subkey]
        return None
    except (json.JSONDecodeError, IOError, OSError, KeyError):
        return None


# ---------------------------------------------------------------------------
# Core check: FATIMA sidecar (.fatima.json)
# ---------------------------------------------------------------------------


def check_fatima_integrity(path: Path) -> list[FatimaDiagnostic]:
    """Check a source module against its FATIMA sidecar attestation.

    Returns an empty list if the sidecar is absent (no attestation
    to check -- not an error, just unattested) or if the seal
    matches. Returns diagnostics for any integrity violations.
    """
    sidecar_path = path.with_suffix(path.suffix + FATIMA_SIDECAR_SUFFIX)
    if not sidecar_path.exists():
        return []

    try:
        with open(sidecar_path) as f:
            data = json.load(f)
        attestation = FatimaAttestation.from_dict(data)
    except (json.JSONDecodeError, KeyError, TypeError) as e:
        return [
            FatimaDiagnostic(
                primitive="fatima_sidecar_corrupt",
                diagnosis=(
                    f"FATIMA sidecar {sidecar_path.name} is corrupt or "
                    f"malformed: {e}. Cannot verify integrity."
                ),
                location=str(path),
                minimal_fix=f"Re-seal the module: furqan-lint seal {path}",
                regression_check=(
                    f"After re-sealing, run `furqan-lint check --fatima "
                    f"{path}` and confirm zero fatima diagnostics."
                ),
            )
        ]

    ok, findings = verify_module(path, attestation)
    if ok:
        return []

    diagnostics: list[FatimaDiagnostic] = []
    for finding in findings:
        diagnostics.append(
            FatimaDiagnostic(
                primitive="fatima_integrity_violation",
                diagnosis=finding,
                location=str(path),
                minimal_fix=(
                    f"If the modification is intentional, re-seal: "
                    f"furqan-lint seal {path}. If unauthorized, "
                    f"restore from the last known-good version."
                ),
                regression_check=(
                    f"After fixing, run `furqan-lint check --fatima "
                    f"{path}` and confirm zero "
                    f"fatima_integrity_violation diagnostics."
                ),
            )
        )
    return diagnostics


# ---------------------------------------------------------------------------
# Enhanced check: Bismillah witness (.witness.bismillah) + bond graph
# ---------------------------------------------------------------------------


def check_fatima_full(
    filepaths: list[str],
    *,
    verify_seals: bool = True,
    check_bonds: bool = True,
) -> list[FatimaDiagnostic]:
    """Run full FATIMA integrity checks on a set of files.

    This is the enhanced entry point (v0.13.0) that checks both
    FATIMA sidecars AND Bismillah witness sidecars, analyzes import
    bond integrity, and produces a hadith-science grade.

    Called from ``runner.py`` via ``check_python_module_with_fatima()``.

    Args:
        filepaths: list of absolute file paths to check.
        verify_seals: whether to verify seal hashes (default True).
        check_bonds: whether to check import bond integrity (default True).

    Returns:
        list of FatimaDiagnostic objects.
    """
    diagnostics: list[FatimaDiagnostic] = []
    sealed_count = 0
    verified_count = 0
    total_count = len(filepaths)

    for filepath in filepaths:
        fp = Path(filepath) if isinstance(filepath, str) else filepath
        if not fp.is_file():
            continue

        # --- Check FATIMA sidecar (.fatima.json) first ---
        fatima_diags = check_fatima_integrity(fp)
        diagnostics.extend(fatima_diags)
        has_fatima_sidecar = fp.with_suffix(
            fp.suffix + FATIMA_SIDECAR_SUFFIX
        ).exists()

        # --- Check Bismillah witness (.witness.bismillah) ---
        witness_path = str(fp) + WITNESS_SIDECAR_SUFFIX
        legacy_path = str(fp) + ".bismillah"

        if os.path.exists(witness_path):
            sealed_count += 1
            if verify_seals:
                try:
                    with open(str(fp), "rb") as f:
                        content = f.read()
                    stored_seal = _extract_witness_seal(witness_path)
                    if stored_seal:
                        computed_seal = _compute_bismillah_seal(content)
                        if hmac_mod.compare_digest(stored_seal, computed_seal):
                            verified_count += 1
                        else:
                            diagnostics.append(FatimaDiagnostic(
                                primitive="fatima_witness_tampered",
                                diagnosis=(
                                    "Bismillah witness seal mismatch: file "
                                    "content has changed since sealing."
                                ),
                                location=str(fp),
                                minimal_fix=(
                                    "Re-seal with the Bismillah encoder: "
                                    f"bismillah_encoder.py seal {fp}"
                                ),
                                regression_check=(
                                    "After re-sealing, run `furqan-lint check "
                                    f"--fatima {fp}` and confirm zero "
                                    "fatima_witness_tampered diagnostics."
                                ),
                                seal_expected=stored_seal,
                                seal_actual=computed_seal,
                            ))
                    else:
                        diagnostics.append(FatimaDiagnostic(
                            primitive="fatima_witness_empty",
                            diagnosis=(
                                "Bismillah witness sidecar exists but "
                                "contains no extractable seal hash."
                            ),
                            location=str(fp),
                            minimal_fix=(
                                "Re-seal with the Bismillah encoder."
                            ),
                            regression_check=(
                                "After re-sealing, verify the witness "
                                "sidecar contains a muhkam_seal key."
                            ),
                        ))
                except (IOError, OSError) as exc:
                    diagnostics.append(FatimaDiagnostic(
                        primitive="fatima_read_error",
                        diagnosis=(
                            f"Could not read file for seal verification: {exc}"
                        ),
                        location=str(fp),
                        minimal_fix="Check file permissions and try again.",
                        regression_check="Verify file is readable.",
                    ))
        elif os.path.exists(legacy_path):
            sealed_count += 1
            # Has legacy sidecar — informational only
            if not has_fatima_sidecar:
                diagnostics.append(FatimaDiagnostic(
                    primitive="fatima_legacy_sidecar",
                    diagnosis=(
                        "File has legacy .bismillah sidecar but no "
                        ".witness.bismillah witness. Consider re-sealing "
                        "with the Bismillah encoder for full FATIMA coverage."
                    ),
                    location=str(fp),
                    minimal_fix=(
                        "Re-seal with the Bismillah encoder: "
                        f"bismillah_encoder.py seal {fp}"
                    ),
                    regression_check=(
                        "After re-sealing, verify .witness.bismillah "
                        "sidecar exists."
                    ),
                ))
        elif not has_fatima_sidecar:
            # No seal of any kind
            diagnostics.append(FatimaDiagnostic(
                primitive="fatima_unsealed",
                diagnosis=(
                    "File has no FATIMA or Bismillah witness sidecar. "
                    "Run 'furqan-lint seal' or 'bismillah_encoder.py seal' "
                    "to create integrity attestation."
                ),
                location=str(fp),
                minimal_fix=f"furqan-lint seal {fp}",
                regression_check=(
                    "After sealing, verify .fatima.json or "
                    ".witness.bismillah sidecar exists."
                ),
            ))

    # --- Bond checking: verify import targets are also sealed ---
    if check_bonds and total_count > 0:
        sealed_paths: set[str] = set()
        for filepath in filepaths:
            fp_str = str(filepath)
            if (os.path.exists(fp_str + WITNESS_SIDECAR_SUFFIX)
                    or os.path.exists(fp_str + FATIMA_SIDECAR_SUFFIX)):
                sealed_paths.add(fp_str)

        for filepath in filepaths:
            fp_str = str(filepath)
            ext = os.path.splitext(fp_str)[1].lower()
            if ext != ".py":
                continue
            try:
                with open(fp_str, "r", encoding="utf-8", errors="replace") as f:
                    source = f.read()
            except (IOError, OSError):
                continue

            for line in source.split("\n"):
                line = line.strip()
                if not (line.startswith("import ") or line.startswith("from ")):
                    continue
                parts = line.split()
                if parts[0] == "from" and len(parts) >= 2:
                    module = parts[1]
                elif parts[0] == "import" and len(parts) >= 2:
                    module = parts[1].rstrip(",")
                else:
                    continue

                base_dir = os.path.dirname(fp_str)
                candidates = [
                    os.path.join(base_dir, module.replace(".", "/") + ".py"),
                    os.path.join(
                        base_dir, module.replace(".", "/"), "__init__.py"
                    ),
                ]
                for candidate in candidates:
                    if (os.path.isfile(candidate)
                            and candidate not in sealed_paths):
                        diagnostics.append(FatimaDiagnostic(
                            primitive="fatima_broken_bond",
                            diagnosis=(
                                f"Import target '{module}' (resolved to "
                                f"{os.path.basename(candidate)}) is not "
                                "sealed. The dependency bond is unprotected."
                            ),
                            location=fp_str,
                            minimal_fix=(
                                f"Seal the dependency: furqan-lint seal "
                                f"{candidate}"
                            ),
                            regression_check=(
                                "After sealing, run `furqan-lint check "
                                f"--fatima {fp_str}` and confirm zero "
                                "fatima_broken_bond diagnostics."
                            ),
                        ))
                        break

    # --- Summary diagnostic with FATIMA grade ---
    if total_count > 0:
        score = (
            verified_count + 0.5 * (sealed_count - verified_count)
        ) / total_count
        score = min(round(score, 4), 1.0)
        grade = _grade_score(score)
        diagnostics.append(FatimaDiagnostic(
            primitive="fatima_grade",
            diagnosis=(
                f"FATIMA integrity grade: {grade} (score: {score:.2f}). "
                f"{verified_count}/{total_count} files verified, "
                f"{sealed_count}/{total_count} sealed."
            ),
            location="",
            minimal_fix="Seal all files for muhkam grade.",
            regression_check=(
                "Run `furqan-lint check --fatima <dir>` and verify "
                "grade meets threshold."
            ),
            grade=grade,
            score=score,
        ))

    return diagnostics


# ---------------------------------------------------------------------------
# Seal operations
# ---------------------------------------------------------------------------


def seal_and_write(path: Path) -> FatimaAttestation:
    """Seal a source module and write the FATIMA sidecar.

    Returns the attestation for display/confirmation.
    """
    attestation = seal_module(path)
    sidecar_path = path.with_suffix(path.suffix + FATIMA_SIDECAR_SUFFIX)
    with open(sidecar_path, "w") as f:
        f.write(attestation.to_json())
        f.write("\n")
    return attestation


def seal_directory(directory: Path) -> list[FatimaAttestation]:
    """Seal all Python source files in a directory tree.

    Returns a list of attestations for display/confirmation.
    """
    attestations: list[FatimaAttestation] = []
    for py_file in sorted(directory.rglob("*.py")):
        att = seal_and_write(py_file)
        attestations.append(att)
    return attestations


