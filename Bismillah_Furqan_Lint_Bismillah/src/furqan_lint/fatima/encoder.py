def _nfc(data: bytes) -> bytes:
    """NFC-normalize bytes (decode as UTF-8, normalize, re-encode)."""
    try:
        text = data.decode("utf-8")
        return unicodedata.normalize("NFC", text).encode("utf-8")
    except (UnicodeDecodeError, UnicodeEncodeError):
        return data


def _name_for_layer(layer_idx: int) -> str:
    """Map layer index to one of the 99 Names.

    154 layers use the 99 Names with 55 repeated (T(10) = F(10) = 55).
    99 + 55 = 154.
    """
    return AL_ASMA_UL_HUSNA[layer_idx % len(AL_ASMA_UL_HUSNA)]


def compute_seal(content_bytes: bytes) -> str:
    """Compute Bismillah-anchored integrity seal (NFC-normalized).

    The seal is SHA-256(Bismillah + NFC(content) + Bismillah).
    """
    h = hashlib.sha256()
    h.update(BISMILLAH.encode("utf-8"))
    h.update(_nfc(content_bytes))
    h.update(BISMILLAH.encode("utf-8"))
    return h.hexdigest()


def compute_heaven_seals(content_bytes: bytes) -> list[str]:
    """Compute per-heaven seals for the 11-heaven architecture.

    Each heaven's seal incorporates its guardian Name and scale.
    This provides structural granularity while the master seal
    (compute_seal) provides the single integrity witness.

    Honest disclosure: all heaven seals are deterministically
    derived from the same content -- they co-fire. The layered
    structure encodes theological meaning, not computational
    independence.
    """
    normalized = _nfc(content_bytes)
    seals = []
    for heaven_idx, (name, scale, guardian) in enumerate(HEAVEN_MAP):
        h = hashlib.sha256()
        h.update(BISMILLAH.encode("utf-8"))
        h.update(f"Heaven {heaven_idx}: {name}".encode("utf-8"))
        h.update(guardian.encode("utf-8"))
        h.update(normalized)
        h.update(BISMILLAH.encode("utf-8"))
        seals.append(h.hexdigest())
    return seals


@dataclass
class FatimaAttestation:
    """FATIMA integrity attestation for a source module.

    Carries the Bismillah-anchored seal, the 11-heaven seal map,
    and metadata for verification.
    """

    module_path: str
    master_seal: str
    heaven_seals: list[str]
    encoder_version: str = "1.0.0"
    architecture: str = "154-layer-dual-constant"
    co_firing_disclosed: bool = True  # honest disclosure

    def to_dict(self) -> dict[str, Any]:
        return {
            "bismillah": BISMILLAH,
            "module_path": self.module_path,
            "master_seal": self.master_seal,
            "heaven_seals": {
                HEAVEN_MAP[i][0]: seal
                for i, seal in enumerate(self.heaven_seals)
            },
            "encoder_version": self.encoder_version,
            "architecture": self.architecture,
            "co_firing_disclosed": self.co_firing_disclosed,
            "total_layers": TOTAL_LAYERS,
            "total_heavens": TOTAL_HEAVENS,
            "layers_per_heaven": LAYERS_PER_HEAVEN,
        }

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "FatimaAttestation":
        heaven_seals = []
        hs_data = data.get("heaven_seals", {})
        for name, _, _ in HEAVEN_MAP:
            heaven_seals.append(hs_data.get(name, ""))
        return cls(
            module_path=data["module_path"],
            master_seal=data["master_seal"],
            heaven_seals=heaven_seals,
            encoder_version=data.get("encoder_version", "1.0.0"),
            architecture=data.get("architecture", "154-layer-dual-constant"),
            co_firing_disclosed=data.get("co_firing_disclosed", True),
        )


def seal_module(path: Path) -> FatimaAttestation:
    """Seal a source module with FATIMA integrity attestation.

    Reads the file, computes the Bismillah-anchored master seal
    and the 11-heaven seal map, and returns a FatimaAttestation.
    """
    content = path.read_bytes()
    return FatimaAttestation(
        module_path=str(path),
        master_seal=compute_seal(content),
        heaven_seals=compute_heaven_seals(content),
    )


def verify_module(
    path: Path, attestation: FatimaAttestation,
) -> tuple[bool, list[str]]:
    """Verify a source module against its FATIMA attestation.

    Returns (ok, findings) where findings lists any mismatches.
    """
    content = path.read_bytes()
    findings: list[str] = []

    current_seal = compute_seal(content)
    if current_seal != attestation.master_seal:
        findings.append(
            f"Master seal mismatch: module has been modified since "
            f"FATIMA attestation. Expected {attestation.master_seal[:16]}..., "
            f"got {current_seal[:16]}..."
        )

    current_heavens = compute_heaven_seals(content)
    for i, (expected, actual) in enumerate(
        zip(attestation.heaven_seals, current_heavens),
    ):
        if expected and expected != actual:
            heaven_name = HEAVEN_MAP[i][0]
            findings.append(
                f"Heaven {i} ({heaven_name}) seal mismatch: "
                f"integrity violation at {HEAVEN_MAP[i][1]} scale"
            )

    return (len(findings) == 0, findings)


